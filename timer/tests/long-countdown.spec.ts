import {test,expect} from '@playwright/test';
test('long countdown labels follow the remaining twelve-hour block',async({page})=>{
 await page.goto('/de/');
 await page.clock.install();
 await page.locator('input[name=hours]').fill('32');
 await page.locator('input[name=minutes]').fill('0');
 await page.locator('.apply-button').click();
 await page.locator('#trigger-timerView').click();
 await page.getByRole('option',{name:'Analog + Digital',exact:true}).click();
 const face=page.locator('#analog-timer');
 await expect(face.locator('text')).toHaveCount(12);
 await expect(face.locator('text').first()).toHaveText('25');
 await expect(face.locator('text').last()).toHaveText('36');
 await expect(face.locator('.timer-hour-hand')).toHaveAttribute('transform','rotate(240 160 160)');
 await page.locator('#start').click();
 await page.clock.fastForward(8*3600000-1000);
 await expect(face.locator('text').last()).toHaveText('36');
 await page.clock.runFor(1000);
 await expect(face.locator('text').first()).toHaveText('13');
 await expect(face.locator('text').last()).toHaveText('24');
 await expect(face.locator('.timer-hour-hand')).toHaveAttribute('transform','rotate(0 160 160)');
 await page.locator('#trigger-analogDesign').click();
 await page.getByRole('option',{name:'Römisch · Eckig',exact:true}).click();
 await expect(face.locator('text').first()).toHaveText('XIII');
 await expect(face.locator('text').last()).toHaveText('XXIV');
 await page.clock.fastForward(12*3600000);
 await expect(face.locator('text').first()).toHaveText('I');
 await expect(face.locator('text').last()).toHaveText('XII');
 await page.locator('input[name=hours]').fill('99');
 await page.locator('.apply-button').click();
 await expect(face.locator('text').first()).toHaveText('XCVII');
 await expect(face.locator('text').last()).toHaveText('CVIII');
 await page.locator('input[name=hours]').fill('0');
 await page.locator('input[name=minutes]').fill('1');
 await page.locator('.apply-button').click();
 await expect(face.locator('text').last()).toHaveText('LX');
 await page.locator('#start').click();
 await page.clock.fastForward(60000);
 await expect(face.locator('text').last()).toHaveText('LX');
 await expect(page.locator('#time')).toHaveText('00:00');
});
