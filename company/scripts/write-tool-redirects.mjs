import {mkdir,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {toolRedirects} from '../src/lib/tool-redirects.ts';
const root=new URL('../',import.meta.url);
let apache='# Generated by scripts/write-tool-redirects.mjs. Merge with existing hosting rules.\n<IfModule mod_rewrite.c>\nRewriteEngine On\n';
let nginx='# Generated tool aliases. Include inside the jacktools.net server block.\n';
for(const [alias,target] of Object.entries(toolRedirects)){
 if(!/^[a-z]+$/.test(alias)||!target.startsWith('https://'))throw new Error('Invalid tool redirect');
 apache+=`RewriteRule ^${alias}/?$ ${target} [R=301,L,NE]\n`;
 for(const path of [`/${alias}`,`/${alias}/`])nginx+=`location = ${path} { return 301 ${target}$is_args$args; }\n`;
}
apache+='</IfModule>\n';
await mkdir(new URL('hosting/',root),{recursive:true});
await writeFile(new URL('dist/.htaccess',root),apache);
await writeFile(new URL('hosting/tool-redirects.nginx.conf',root),nginx);
console.log(`Generated ${Object.keys(toolRedirects).length} permanent tool redirects in ${fileURLToPath(new URL('dist/.htaccess',root))}`);
